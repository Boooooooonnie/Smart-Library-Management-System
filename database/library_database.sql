-- 預存程序：建立借閱紀錄
CREATE PROCEDURE sp_AddBorrowRecord
    @borrow_id VARCHAR(10),
    @user_id VARCHAR(10),
    @book_id VARCHAR(10),
    @borrow_date DATETIME,
    @due_date DATETIME
AS
BEGIN
    SET NOCOUNT ON;
    BEGIN TRY
        BEGIN TRANSACTION;
        -- 新增至 Borrows
        INSERT INTO Borrows (borrow_id, user_id, borrow_date, due_date)
        VALUES (@borrow_id, @user_id, @borrow_date, @due_date);
        -- 新增至 BorrowItems
        INSERT INTO BorrowItems (borrow_id, book_id)
        VALUES (@borrow_id, @book_id);
        -- 更新書籍狀態為「被借閱未歸還」
        UPDATE Books
        SET book_status_id = 2
        WHERE book_id = @book_id;
        COMMIT TRANSACTION;
        PRINT '借閱紀錄已成功新增。';
    END TRY
    BEGIN CATCH
        ROLLBACK TRANSACTION;
        PRINT '發生錯誤，借閱紀錄未新增。';
    END CATCH
END;
GO
EXEC sp_AddBorrowRecord 'BR050', 'U002', 'B008', '2025-11-10', '2025-11-24';
