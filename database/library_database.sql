-- 預存程序：更新歸還日期
CREATE PROCEDURE sp_UpdateReturnDate
    @borrow_id VARCHAR(10),
    @book_id VARCHAR(10),
    @return_date DATETIME
AS
BEGIN
    SET NOCOUNT ON;
    UPDATE BorrowItems
    SET return_date = @return_date
    WHERE borrow_id = @borrow_id AND book_id = @book_id;
    UPDATE Books
    SET book_status_id = 1
    WHERE book_id = @book_id;
    PRINT '歸還資料已更新。';
END;
GO

CREATE FUNCTION fn_GetOverdueDays
(
    @due_date DATETIME,
    @return_date DATETIME
)
RETURNS INT
AS
BEGIN
    DECLARE @days INT;
    IF @return_date IS NULL OR @return_date <= @due_date
        SET @days = 0;
    ELSE
        SET @days = DATEDIFF(DAY, @due_date, @return_date);
    RETURN @days;
END;
GO
CREATE FUNCTION fn_CountUserBorrowedBooks
(
    @user_id VARCHAR(10)
)
RETURNS INT
AS
BEGIN
    DECLARE @count INT;
    SELECT @count = COUNT(*)
    FROM Borrows b
    JOIN BorrowItems bi ON b.borrow_id = bi.borrow_id
    WHERE b.user_id = @user_id AND bi.return_date IS NULL;
    RETURN @count;
END;
GO

CREATE TRIGGER trg_AfterBorrowInsert
ON BorrowItems
AFTER INSERT
AS
BEGIN
    UPDATE Books
    SET book_status_id = 2
    WHERE book_id IN (SELECT book_id FROM inserted);
END;
GO
CREATE TRIGGER trg_AfterReturnUpdate
ON BorrowItems
AFTER UPDATE
AS
BEGIN
    UPDATE Books
    SET book_status_id = 1
    WHERE book_id IN (
        SELECT book_id FROM inserted WHERE return_date IS NOT NULL
    );
END;
GO

