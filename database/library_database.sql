CREATE database library_system3;
GO
USE library_system3;
GO
CREATE TABLE Users (
    user_id VARCHAR(10) NOT NULL PRIMARY KEY,
    user_name NVARCHAR(100) NOT NULL,
    user_phone NVARCHAR(20),
    user_email NVARCHAR(255) UNIQUE,
    user_password NVARCHAR(255) NOT NULL,
    created_at DATETIME DEFAULT GETDATE()
);
GO
CREATE TABLE Categories (
    category_id INT NOT NULL PRIMARY KEY,
    category_name NVARCHAR(100) NOT NULL UNIQUE
);
GO
CREATE TABLE BookStatuses (
    book_status_id INT NOT NULL PRIMARY KEY,
    book_status_name NVARCHAR(50) NOT NULL UNIQUE
);
GO
CREATE TABLE Books (
    book_id VARCHAR(10) NOT NULL PRIMARY KEY,
    book_name NVARCHAR(255) NOT NULL,
    author NVARCHAR(255),
    publisher NVARCHAR(255),
    book_isbn VARCHAR(50) UNIQUE,
    publish_year INT,
    category_id INT,
    book_status_id INT,
    created_at DATETIME DEFAULT GETDATE(),
    CONSTRAINT FK_Books_Category FOREIGN KEY (category_id) REFERENCES Categories(category_id),
    CONSTRAINT FK_Books_Status FOREIGN KEY (book_status_id) REFERENCES BookStatuses(book_status_id)
);
GO
CREATE TABLE Borrows (
    borrow_id VARCHAR(10) NOT NULL PRIMARY KEY,
    user_id VARCHAR(10) NOT NULL,
    borrow_date DATETIME NOT NULL,
    due_date DATETIME,
    created_at DATETIME DEFAULT GETDATE(),
    CONSTRAINT FK_Borrows_User FOREIGN KEY (user_id) REFERENCES Users(user_id)
);
GO
CREATE TABLE BorrowItems (
    borrow_id VARCHAR(10) NOT NULL,
    book_id VARCHAR(10) NOT NULL,
    return_date DATETIME,
    renewed BIT DEFAULT 0,
    created_at DATETIME DEFAULT GETDATE(),
    CONSTRAINT PK_BorrowItems PRIMARY KEY (borrow_id, book_id),
    CONSTRAINT FK_BorrowItems_Borrow FOREIGN KEY (borrow_id) REFERENCES Borrows(borrow_id),
    CONSTRAINT FK_BorrowItems_Book FOREIGN KEY (book_id) REFERENCES Books(book_id)
);
GO
CREATE TABLE ReservationStatuses (
    reservation_status_id INT NOT NULL PRIMARY KEY,
    reservation_status_name NVARCHAR(50) NOT NULL UNIQUE
);
GO
CREATE TABLE Reservations (
    reservation_id VARCHAR(10) NOT NULL PRIMARY KEY,
    user_id VARCHAR(10) NOT NULL,
    reservation_date DATETIME NOT NULL,
    reservation_status_id INT,
    created_at DATETIME DEFAULT GETDATE(),
    CONSTRAINT FK_Reservations_User FOREIGN KEY (user_id) REFERENCES Users(user_id),
    CONSTRAINT FK_Reservations_Status FOREIGN KEY (reservation_status_id) REFERENCES ReservationStatuses(reservation_status_id)
);
GO
CREATE TABLE ReservationItems (
    reservation_id VARCHAR(10) NOT NULL,
    book_id VARCHAR(10) NOT NULL,
    created_at DATETIME DEFAULT GETDATE(),
    CONSTRAINT PK_ReservationItems PRIMARY KEY (reservation_id, book_id),
    CONSTRAINT FK_ReservationItems_Reservation FOREIGN KEY (reservation_id) REFERENCES Reservations(reservation_id),
    CONSTRAINT FK_ReservationItems_Book FOREIGN KEY (book_id) REFERENCES Books(book_id)
);
GO
